%% Plot TX, Before Channel Inversion, and After Channel Inversion Constellations
clear; clc; close all;

% === SELECT MODULATION SCHEME & SNR HERE ===
mod_scheme = '16QAM';                     % Options: 'BPSK', 'QPSK', '16QAM'
Eb_N0_dB_test = 5;                       % Adjust SNR (e.g., 10, 15, or 25 dB)
Eb_N0_lin_test = 10^(Eb_N0_dB_test / 10);

% 1. Run Transmitter, Channel, and Receiver Scripts
TX;                                       % Generates b_k, x_k, tx_const, ref_const, Eb, N_sym
N0 = Eb / Eb_N0_lin_test;                 % Noise PSD for the chosen Eb/N0
rayleigh_channel;                         % Generates h, h_upsampled, r_t
RX;                                       % Generates rx_before_inv, rx_after_inv, b_hat

% Choose clean plot limits depending on modulation scheme
if strcmpi(strrep(mod_scheme, '-', ''), '16QAM')
    tx_lim = [-4.5, 4.5];
    rx_lim = [-6.5, 6.5];
else
    tx_lim = [-2, 2];
    rx_lim = [-3.5, 3.5];
end

% Plot up to 5000 symbols so the GUI scopes render fast
num_pts = min(N_sym, 5000);

%% 1. Transmitter Constellation Scope (x_k)
const_tx = comm.ConstellationDiagram( ...
    'Name', sprintf('1. %s Transmitter Constellation', mod_scheme), ...
    'Title', sprintf('Transmitted %s Symbols (x_k)', mod_scheme), ...
    'ReferenceConstellation', ref_const, ...
    'ShowTrajectory', false, ...
    'XLimits', tx_lim, ...
    'YLimits', tx_lim);

const_tx(tx_const(1:num_pts));

%% 2. Constellation Scope BEFORE Channel Inversion
const_before = comm.ConstellationDiagram( ...
    'Name', sprintf('2. %s Before Channel Inversion', mod_scheme), ...
    'Title', sprintf('%s Before Channel Inversion (Eb/N0 = %d dB)', mod_scheme, Eb_N0_dB_test), ...
    'ReferenceConstellation', ref_const, ...
    'ShowTrajectory', false, ...
    'XLimits', rx_lim, ...
    'YLimits', rx_lim);

const_before(rx_before_inv(1:num_pts).');

%% 3. Constellation Scope AFTER Channel Inversion
const_after = comm.ConstellationDiagram( ...
    'Name', sprintf('3. %s After Channel Inversion', mod_scheme), ...
    'Title', sprintf('%s After Channel Inversion (Eb/N0 = %d dB)', mod_scheme, Eb_N0_dB_test), ...
    'ReferenceConstellation', ref_const, ...
    'ShowTrajectory', false, ...
    'XLimits', rx_lim, ...
    'YLimits', rx_lim);

const_after(rx_after_inv(1:num_pts).');